import test from 'node:test';
import assert from 'node:assert/strict';
import { createDecipheriv, randomUUID } from 'node:crypto';
import pg from 'pg';
import { hashToken } from '../../services/identity-service/src/utils/crypto.js';

test('HTTP auth flow enforces Origin, rotates cookie, and rejects reuse', {
  skip: !process.env.IDENTITY_TEST_DATABASE_URL || !process.env.IDENTITY_TEST_API_URL || !process.env.IDENTITY_MAIL_KEY,
}, async () => {
  const db = new pg.Client({ connectionString: process.env.IDENTITY_TEST_DATABASE_URL });
  await db.connect();
  const base = `${process.env.IDENTITY_TEST_API_URL}/api/v2/auth`;
  const origin = process.env.IDENTITY_TEST_ORIGIN || 'http://localhost:5173';
  const email = `${randomUUID()}@example.test`;
  const password = 'abcdefg!';
  const post = async (path, body, cookie, authorization, requestOrigin = origin) => {
    const response = await fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: requestOrigin, ...(cookie ? { Cookie: cookie } : {}), ...(authorization ? { Authorization: `Bearer ${authorization}` } : {}) }, body: JSON.stringify(body) });
    return { response, body: await response.json() };
  };
  const readToken = async (recipient, purpose) => {
    const { rows } = await db.query('SELECT nonce,ciphertext,tag FROM identity_email_outbox WHERE recipient=$1 AND purpose=$2 ORDER BY id DESC LIMIT 1', [recipient, purpose]);
    assert.equal(rows.length, 1);
    const decipher = createDecipheriv('aes-256-gcm', Buffer.from(process.env.IDENTITY_MAIL_KEY, 'base64'), rows[0].nonce);
    decipher.setAuthTag(rows[0].tag);
    return Buffer.concat([decipher.update(rows[0].ciphertext), decipher.final()]).toString('utf8');
  };
  try {
    const denied = await post('/register', { email, fullName: 'Test User', password, confirmPassword: password }, null, null, 'https://evil.example');
    assert.equal(denied.response.status, 403);
    const registration = await post('/register', { email, fullName: 'Test User', password, confirmPassword: password });
    assert.equal(registration.response.status, 201);
    assert.equal(JSON.stringify(registration.body).includes(password), false);
    assert.equal(registration.body.requiresEmailVerification, true);
    assert.equal(registration.body.user.emailVerifiedAt, null);
    const verificationToken = await readToken(email, 'verify_email');
    assert.equal((await post('/login', { email, password })).response.status, 401);
    assert.equal((await post('/resend-verification', { email })).response.status, 200);
    const resentToken = await readToken(email, 'verify_email');
    assert.notEqual(resentToken, verificationToken);
    assert.equal((await post('/verify-email', { email, token: verificationToken })).response.status, 400);
    assert.equal((await post('/verify-email', { email, token: resentToken })).response.status, 200);
    assert.equal((await post('/verify-email', { email, token: resentToken })).response.status, 400);
    const login = await post('/login', { email, password });
    assert.equal(login.response.status, 200);
    assert.ok(login.body.accessToken);
    assert.equal('refreshToken' in login.body, false);
    const firstCookie = login.response.headers.get('set-cookie');
    assert.match(firstCookie, /HttpOnly/i);
    assert.match(firstCookie, /SameSite=Strict/i);
    const me = await fetch(base + '/me', { headers: { Authorization: `Bearer ${login.body.accessToken}` } });
    assert.equal(me.status, 200);
    const profileBase = `${process.env.IDENTITY_TEST_API_URL}/api/v2/users/me`;
    const authHeaders = { Authorization: `Bearer ${login.body.accessToken}`, Origin: origin };
    const profileResponse = await fetch(profileBase, { headers: authHeaders });
    const profile = await profileResponse.json();
    assert.equal(profileResponse.status, 200);
    assert.equal(profile.email, email);
    assert.equal('password_hash' in profile, false);
    const updateResponse = await fetch(profileBase, { method: 'PATCH', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ displayName: 'Updated Buyer' }) });
    assert.equal(updateResponse.status, 200);
    const preferenceResponse = await fetch(`${profileBase}/preferences`, { method: 'PATCH', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ marketingOptIn: true }) });
    assert.equal((await preferenceResponse.json()).marketingOptIn, true);
    const addressResponse = await fetch(`${profileBase}/addresses`, { method: 'POST', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ receiverName: 'Receiver Name', receiverPhone: '+84901234567', provinceCode: '79', districtCode: '760', wardCode: '26734', addressLine: '123 Main Street' }) });
    const createdAddress = (await addressResponse.json()).address;
    assert.equal(addressResponse.status, 201);
    assert.equal(createdAddress.isDefault, true);
    const listResponse = await fetch(`${profileBase}/addresses`, { headers: authHeaders });
    const listed = await listResponse.json();
    assert.equal('receiverPhone' in listed.addresses[0], false);
    const detailResponse = await fetch(`${profileBase}/addresses/${createdAddress.id}`, { headers: authHeaders });
    assert.equal((await detailResponse.json()).address.receiverPhone, '+84901234567');
    const exportResponse = await fetch(`${profileBase}/data-export`, { headers: authHeaders });
    const exported = await exportResponse.json();
    assert.equal(exportResponse.status, 200);
    assert.equal(exported.scope, 'identity-service');
    assert.equal(exported.addresses[0].receiverPhone, '+84901234567');
    assert.equal(JSON.stringify(exported).includes('password_hash'), false);
    assert.equal((await fetch(`${profileBase}/data-export`)).status, 401);
    const deletionHeaders = { ...authHeaders, 'Content-Type': 'application/json' };
    assert.equal((await fetch(`${profileBase}/deletion-request`, { method: 'POST', headers: deletionHeaders,
      body: JSON.stringify({ password: 'wrong-password' }) })).status, 401);
    const deletionResponse = await fetch(`${profileBase}/deletion-request`, { method: 'POST', headers: deletionHeaders,
      body: JSON.stringify({ password }) });
    assert.equal(deletionResponse.status, 202);
    const deletion = await deletionResponse.json();
    assert.equal(deletion.request.status, 'PENDING');
    assert.equal((await (await fetch(`${profileBase}/deletion-request`, { headers: authHeaders })).json()).request.id, deletion.request.id);
    assert.equal((await fetch(`${profileBase}/deletion-request`, { method: 'DELETE', headers: authHeaders })).status, 200);
    const stranger = await post('/register', { email: `${randomUUID()}@example.test`, fullName: 'Stranger User', password, confirmPassword: password });
    const strangerToken = await readToken(stranger.body.user.email, 'verify_email');
    assert.equal((await post('/verify-email', { email: stranger.body.user.email, token: strangerToken })).response.status, 200);
    const strangerLogin = await post('/login', { email: stranger.body.user.email, password });
    const forbiddenAddress = await fetch(`${profileBase}/addresses/${createdAddress.id}`, { headers: { Authorization: `Bearer ${strangerLogin.body.accessToken}` } });
    assert.equal(forbiddenAddress.status, 404);
    const rotated = await post('/refresh', {}, firstCookie.split(';')[0]);
    assert.equal(rotated.response.status, 200);
    const newCookie = rotated.response.headers.get('set-cookie');
    assert.notEqual(newCookie.split(';')[0], firstCookie.split(';')[0]);
    const reuse = await post('/refresh', {}, firstCookie.split(';')[0]);
    assert.equal(reuse.response.status, 401);
    const stolenFamily = await post('/refresh', {}, newCookie.split(';')[0]);
    assert.equal(stolenFamily.response.status, 401);
    const second = await post('/login', { email, password });
    const logout = await post('/logout', {}, second.response.headers.get('set-cookie').split(';')[0], second.body.accessToken);
    assert.equal(logout.response.status, 200);
    assert.equal((await post('/refresh', {}, second.response.headers.get('set-cookie').split(';')[0])).response.status, 401);
    const beforeReset = await post('/login', { email, password });
    const unknownReset = await post('/forgot-password', { email: `${randomUUID()}@example.test` });
    const knownReset = await post('/forgot-password', { email });
    assert.deepEqual(unknownReset.body, knownReset.body);
    const oldResetCode = await readToken(email, 'reset_password');
    assert.match(oldResetCode, /^\d{6}$/);
    assert.equal((await post('/forgot-password', { email })).response.status, 200);
    const resetCode = await readToken(email, 'reset_password');
    assert.notEqual(resetCode, oldResetCode);
    const newPassword = 'newpass!';
    assert.equal((await post('/reset-password', { email, code: oldResetCode, newPassword, confirmPassword: newPassword })).response.status, 400);
    assert.equal((await post('/reset-password', { email, code: resetCode, newPassword, confirmPassword: newPassword })).response.status, 200);
    assert.equal((await post('/reset-password', { email, code: resetCode, newPassword, confirmPassword: newPassword })).response.status, 400);
    assert.equal((await post('/refresh', {}, beforeReset.response.headers.get('set-cookie').split(';')[0])).response.status, 401);
    assert.equal((await fetch(base + '/me', { headers: { Authorization: `Bearer ${beforeReset.body.accessToken}` } })).status, 401);
    assert.equal((await post('/login', { email, password: newPassword })).response.status, 200);

    const rateEmail = `${randomUUID()}@example.test`;
    assert.equal((await post('/register', { email: rateEmail, fullName: 'Rate Test', password, confirmPassword: password })).response.status, 201);
    assert.equal((await post('/verify-email', { email: rateEmail, token: await readToken(rateEmail, 'verify_email') })).response.status, 200);
    for (let i = 0; i < 5; i++) assert.equal((await post('/login', { email: rateEmail, password: 'incorrect-password' })).response.status, 401);
    assert.equal((await post('/login', { email: rateEmail, password })).response.status, 429);
    await db.query("UPDATE auth_rate_limits SET window_start=now()-interval '16 minutes' WHERE bucket=$1", [`login:account:${hashToken(rateEmail)}`]);
    assert.equal((await post('/login', { email: rateEmail, password })).response.status, 200);
  } finally { await db.end(); }
});
